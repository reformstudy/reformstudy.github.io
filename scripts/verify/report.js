/** Markdown views of verification reports (provenance/reports/*.md). */

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const short = (s, n = 120) => (s.length > n ? `${s.slice(0, n)}…` : s);

function ourReading(item) {
  if (!item.context) return `**${esc(item.ours) || '(none)'}**`;
  const [before, after] = item.context;
  return short(`${before ? `…${esc(before)} ` : ''}**${esc(item.ours) || '(nothing)'}**${after ? ` ${esc(after)}…` : ''}`, 200);
}

function readingsCell(item, ids) {
  return ids.map(id => {
    const r = item.readings[id];
    return `${id.replace(/^[a-z]+-/, '')}: ${r === undefined ? '—' : `“${esc(short(r))}”`}`;
  }).join('<br>');
}

export function renderReport(r) {
  const ids = Object.keys(r.witnesses);
  const out = [];
  out.push(`# Verification: ${r.title}`, '');
  out.push(`Generated by \`npm run verify -- ${r.resource}\` on ${r.checked}. Review with \`npm run review -- ${r.resource}\`.`, '');
  out.push(`**${r.pending.length} awaiting review**, ${r.corrections} corrections, ${r.accepted} accepted and ${r.ignored ?? 0} ignored differences on record${r.stale.length ? `, **${r.stale.length} earlier decisions no longer match** (the source or a witness changed; review them again)` : ''}.`, '');
  if (r.awaitingSignOff) out.push(`${r.awaitingSignOff} of the decisions on record were made by Claude and await a person's sign-off (\`npm run review -- ${r.resource} confirm\`).`, '');

  out.push('## Copies compared', '');
  out.push('| | Pinned at | Lineage | Units | Places differing |', '|---|---|---|---|---|');
  out.push(`| Source | ${r.source.pin} | ${r.source.lineage} | ${r.stats.units} | |`);
  for (const [id, w] of Object.entries(r.witnesses)) out.push(`| ${id}: ${esc(w.title)} | ${w.pin} | ${w.lineage} | ${w.unitsCovered} | ${w.placesDiffering} |`);
  out.push('', `Compared: ${r.comparison}`, '');

  const s = r.stats;
  out.push('## Results', '');
  out.push(`- ${s.agree} ${r.unitName === 'entry' ? 'entries' : `${r.unitName}s`} or places where every witness agrees with us`);
  out.push(`- ${s.majority} places where a witness differs but we have the majority (not reviewed)`);
  out.push(`- ${s.against} places where independent witnesses agree against us`);
  out.push(`- ${s.split} places where the witnesses are split, or a single witness differs`);
  if (s.unattested) out.push(`- ${s.unattested} units no witness has`);
  out.push('');

  if (r.pending.length) {
    out.push('## Awaiting review', '');
    out.push(`Accept a difference (our reading stands) with \`npm run review -- ${r.resource} accept <id> --reason "…"\`, or a whole suggested class with \`--class <class>\` after checking a sample. Correct the source with \`npm run review -- ${r.resource} correct <id> --to "…"\`.`, '');
    const groups = new Map();
    for (const item of r.pending) {
      const k = item.suggestion?.class ?? 'unclassified';
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push(item);
    }
    // Items that need judgement first; classes with a suggested bulk action last.
    const ordered = [...groups].sort((x, y) => (x[1][0].suggestion?.action === 'accept') - (y[1][0].suggestion?.action === 'accept'));
    for (const [cls, items] of ordered) {
      const sug = items[0].suggestion ?? {};
      out.push(`### ${cls} (${items.length})`, '');
      if (sug.note) out.push(`${sug.note}${sug.action ? ` Suggested: **${sug.action}**.` : ''}`, '');
      out.push('| id | unit | ours | witnesses | |', '|---|---|---|---|---|');
      for (const item of items) out.push(`| \`${item.id}\` | ${esc(item.unit)} | ${ourReading(item)} | ${readingsCell(item, ids)} | ${item.class} |`);
      out.push('');
    }
  }
  if (r.stale.length) {
    out.push('## Accepted decisions that no longer match', '');
    for (const a of r.stale) out.push(`- ${a.unit}: “${esc(a.ours)}” (key ${a.key.slice(0, 10)})`);
    out.push('');
  }
  return out.join('\n');
}

export function renderIndex(reports, registry) {
  const out = ['# Source verification', ''];
  out.push('Generated by `npm run verify`. Provenance for every source and witness is in [registry.json](../registry.json); reviewed decisions are in [decisions/](../decisions/). Method: [res/SOURCES.md](../../res/SOURCES.md).', '');
  out.push('| Resource | Witnesses | Corrections | Accepted | Awaiting review | Awaiting sign-off | Checked |', '|---|---|---|---|---|---|---|');
  for (const [id, src] of Object.entries(registry.sources)) {
    const r = reports[id];
    if (!r) {
      out.push(`| ${src.title} | ${src.witnesses.length ? src.witnesses.join(', ') : 'none reachable'} | | | not verified | | |`);
      continue;
    }
    out.push(`| [${r.title}](${id}.md) | ${Object.keys(r.witnesses).join(', ')} | ${r.corrections} | ${r.accepted} | ${r.pending.length + r.stale.length} | ${r.awaitingSignOff ?? 0} | ${r.checked} |`);
  }
  const open = registry.attestations.filter(a => a.status !== 'confirmed');
  if (open.length) {
    out.push('', '## Open attestations', '', 'Facts a comparison cannot establish, still to be confirmed by a person:', '');
    for (const a of open) out.push(`- **${a.subject}**: ${a.claim} ${a.note ?? ''}`);
  }
  return out.join('\n') + '\n';
}
