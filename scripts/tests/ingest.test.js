/** A small valid Bible: every chapter has verses 1–3. */
function syntheticBible(id) {
  return {
    version: { id },
    books: CANON.map(b => ({
      id: b.id, name: b.name, testament: b.testament, chapters: b.chapters,
      verses: Array.from({ length: b.chapters }, (_, c) => [1, 2, 3].map(v => ({
        book: b.id, chapter: c + 1, verse: v, text: `Verse ${v}.`,
      }))).flat(),
    })),
  };
}

test('validateBible passes a well-formed translation', () => {
  const r = validateBible(syntheticBible('web'), 'web');
  assert.deepEqual(r.errors, []);
  assert.deepEqual(r.warnings, []);
});

test('validateBible reports missing chapters, duplicates and stray whitespace as errors', () => {
  const bible = syntheticBible('web');
  const oba = bible.books.find(b => b.id === 'OBA');
  oba.verses = [];
  const gen = bible.books[0];
  gen.verses.splice(1, 0, { ...gen.verses[0] });
  gen.verses[5].text = ' padded ';
  const r = validateBible(bible, 'web');
  assert.ok(r.errors.some(e => e.includes('OBA 1 has no verses')));
  assert.ok(r.errors.some(e => e.includes('GEN 1:1 appears twice')));
  assert.ok(r.errors.some(e => e.includes('stray whitespace')));
});

test('validateBible warns about verses the KJV has and a translation omits', () => {
  const kjv = syntheticBible('kjv');
  const bsb = syntheticBible('bsb');
  const act = bsb.books.find(b => b.id === 'ACT');
  act.verses = act.verses.filter(v => !(v.chapter === 8 && v.verse === 2));
  const r = validateBible(bsb, 'bsb', { reference: kjv });
  assert.deepEqual(r.errors, []);
  assert.ok(r.warnings.some(w => w.includes('ACT 8: verse numbers jump from 1 to 3')));
  assert.ok(r.warnings.some(w => w.includes('ACT 8: no verse 2 (present in the KJV)')));
});

test('validateBible holds the KJV to a gap-free 31,102 verses', () => {
  const r = validateBible(syntheticBible('kjv'), 'kjv');
  assert.ok(r.errors.some(e => e.includes('expected 31102')));
});

test('validateConfession checks proof references against the KJV', () => {
  const conf = refs => ({
    confession: { id: 'wcf' },
    sections: [{ chapter: 1, sections: [{ number: '1.1', content: 'Text', contentWithProofs: 'Text[1]', proofs: [{ id: 1, refs }] }] }],
  });
  const kjv = syntheticBible('kjv');
  assert.deepEqual(validateConfession(conf(['PSA.19.1-3']), 'wcf', { reference: kjv }).errors, []);
  assert.ok(validateConfession(conf(['PSA.19.4']), 'wcf', { reference: kjv }).errors.some(e => e.includes('"PSA.19.4" is not in the KJV')));
  assert.ok(validateConfession(conf(['Ps 19:1']), 'wcf', { reference: kjv }).errors.some(e => e.includes("can't read")));
});

test("validateStrongs requires ordered, prefixed numbers", () => {
  const data = nums => ({ concordance: { totalEntries: nums.length }, entries: nums.map(n => ({ number: n, definition: 'd' })) });
  assert.deepEqual(validateStrongs(data(['G1', 'G2', 'G10']), 'greek').errors, []);
  assert.ok(validateStrongs(data(['G2', 'G1']), 'greek').errors.some(e => e.includes('out of order')));
  assert.ok(validateStrongs(data(['H1']), 'greek').errors.some(e => e.includes('should look like G123')));
});

test('applyWcfCorrections fixes wording in both texts and swaps proof references', () => {
  const source = { Data: [{ Chapter: '8', Title: 'T', Sections: [{
    Section: '1', Content: 'beside it, in matters', ContentWithProofs: 'beside it, in matters[1]',
    Proofs: [{ Id: 1, References: ['Isa.42.1', '2Tim.2.5', 'Heb.1.2'] }],
  }] }] };
  const out = applyWcfCorrections(source, {
    text: [{ section: '8.1', from: 'beside it, in matters', to: 'beside it, if matters' }],
    proofs: [{ section: '8.1', footnote: 1, replace: ['2Tim.2.5'], with: ['1Tim.2.5'] }],
  });
  const s = out.Data[0].Sections[0];
  assert.equal(s.Content, 'beside it, if matters');
  assert.equal(s.ContentWithProofs, 'beside it, if matters[1]');
  assert.deepEqual(s.Proofs[0].References, ['Isa.42.1', '1Tim.2.5', 'Heb.1.2']);
  assert.equal(source.Data[0].Sections[0].Content, 'beside it, in matters', 'source is not modified');
  assert.throws(() => applyWcfCorrections(source, { proofs: [{ section: '8.1', footnote: 1, replace: ['Rom.1.1'], with: [] }] }), /expected Rom.1.1/);
});

test('digestFiles ignores order and records missing files', () => {
  const a = digestFiles(new Map([['b.json', Buffer.from('2')], ['a.json', Buffer.from('1')], ['c.json', null]]));
  const b = digestFiles(new Map([['c.json', null], ['a.json', Buffer.from('1')], ['b.json', Buffer.from('2')]]));
  assert.deepEqual(a, b);
  assert.equal(a.files, 3);
  assert.notEqual(digestFiles(new Map([['a.json', Buffer.from('1')]])).sha256, digestFiles(new Map([['a.json', Buffer.from('x')]])).sha256);
});

test('checkLock rejects a changed or unknown source', () => {
  assert.throws(() => checkLock('wcf', { sha256: '0'.repeat(64) }, { update: false }), /has changed since it was verified/);
  assert.throws(() => checkLock('no-such-source', { sha256: '0'.repeat(64) }, { update: false }), /No sources\.no-such-source/);
});
