test('parseUsfmBook moves Psalm titles out of verse 1 and strips markup', () => {
  const usfm = [
    '\\id PSA Autogenerated BSB',
    '\\c 1',
    '\\ms BOOK I',
    '\\d Psalms 1–41',
    '\\s1 The Two Paths',
    '\\r (\\ref Matthew 5:3–12|MAT 5:3-12\\ref*)',
    '\\q1 \\v 1 Blessed \\add is\\add* the man',
    '\\q2 who does not walk in the counsel of the wicked,',
    '\\b ',
    '\\q1 \\v 2 But his delight \\add is\\add* in the Law of the LORD.',
    '\\c 3',
    '\\d \\v 1 A Psalm of David, when he fled.\\f + \\fr 3:1 \\ft A note with \\ref Genesis 1:1|GEN 1:1\\ref*.\\f*',
    '\\q1 O LORD, how my foes have increased!',
    '\\q1 \\v 2 Many say of me,',
    '\\qr Selah\\f + \\fr 3:2 \\fqa Selah \\ft or \\fqa Interlude\\f*',
    '\\p \\wj “Follow Me,”\\wj* He said.',
  ].join('\n');
  const { verses, subtitles } = parseUsfmBook(usfm, 'PSA');
  assert.deepEqual(verses.map(v => [v.chapter, v.verse, v.text]), [
    [1, 1, 'Blessed is the man who does not walk in the counsel of the wicked,'],
    [1, 2, 'But his delight is in the Law of the LORD.'],
    [3, 1, 'O LORD, how my foes have increased!'],
    [3, 2, 'Many say of me, Selah “Follow Me,” He said.'],
  ]);
  assert.deepEqual(subtitles, { 3: 'A Psalm of David, when he fled.' });
});

